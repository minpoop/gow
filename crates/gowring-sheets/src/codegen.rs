//! Turn the sheets into Rust: one struct per sheet (its columns are the fields), one literal per row.

use crate::model::{ColType, Column, Sheet, Sheets};
use serde_json::Value;
use std::collections::BTreeMap;
use std::fmt::Write;

pub fn pascal(s: &str) -> String {
    s.split('_')
        .filter(|p| !p.is_empty())
        .map(|p| {
            let mut c = p.chars();
            match c.next() {
                Some(f) => f.to_ascii_uppercase().to_string() + c.as_str(),
                None => String::new(),
            }
        })
        .collect()
}

fn enum_name(sheet: &Sheet, col: &Column) -> String {
    col.enum_name.clone().unwrap_or_else(|| {
        let prefix = sheet.struct_name.strip_suffix("Def").unwrap_or(&sheet.struct_name);
        format!("{prefix}{}", pascal(&col.name))
    })
}

fn field_type(sheet: &Sheet, col: &Column) -> String {
    match col.ty {
        ColType::Id | ColType::Str | ColType::Text | ColType::Ref => "&'static str".into(),
        ColType::RefOpt => "Option<&'static str>".into(),
        ColType::Int => "i32".into(),
        ColType::Float => "f32".into(),
        ColType::Bool => "bool".into(),
        ColType::Color => "u32".into(),
        ColType::Enum => enum_name(sheet, col),
        ColType::ListRef => "&'static [&'static str]".into(),
        ColType::ListEnum => format!("&'static [{}]", enum_name(sheet, col)),
    }
}

fn literal(sheet: &Sheet, col: &Column, v: &Value) -> String {
    match col.ty {
        ColType::Id | ColType::Str | ColType::Text | ColType::Ref => format!("{:?}", v.as_str().unwrap()),
        ColType::RefOpt => match v.as_str() {
            Some(s) => format!("Some({s:?})"),
            None => "None".into(),
        },
        ColType::Int => format!("{}", v.as_i64().unwrap()),
        ColType::Float => format!("{:?}", v.as_f64().unwrap()),
        ColType::Bool => format!("{}", v.as_bool().unwrap()),
        ColType::Color => format!("0x{}", &v.as_str().unwrap()[1..].to_uppercase()),
        ColType::Enum => format!("{}::{}", enum_name(sheet, col), pascal(v.as_str().unwrap())),
        ColType::ListRef => {
            let items: Vec<String> = v.as_array().unwrap().iter().map(|x| format!("{:?}", x.as_str().unwrap())).collect();
            format!("&[{}]", items.join(", "))
        }
        ColType::ListEnum => {
            let en = enum_name(sheet, col);
            let items: Vec<String> =
                v.as_array().unwrap().iter().map(|x| format!("{en}::{}", pascal(x.as_str().unwrap()))).collect();
            format!("&[{}]", items.join(", "))
        }
    }
}

/// Generate the Rust source for every sheet. The sheets must have passed preflight.
pub fn generate(sheets: &Sheets) -> String {
    let mut out = String::new();
    out.push_str("// @generated by gowring-sheets from design/*.json. Do not edit: change the sheet.\n");
    out.push_str("\n");

    // Enums (shared by name; value sets must agree).
    let mut enums: BTreeMap<String, Vec<String>> = BTreeMap::new();
    for sheet in &sheets.sheets {
        for col in &sheet.columns {
            if matches!(col.ty, ColType::Enum | ColType::ListEnum) {
                let name = enum_name(sheet, col);
                match enums.get(&name) {
                    Some(existing) if *existing != col.values => {
                        panic!("enum `{name}` is declared with two different value sets")
                    }
                    _ => {
                        enums.insert(name, col.values.clone());
                    }
                }
            }
        }
    }
    for (name, values) in &enums {
        let _ = writeln!(out, "#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, PartialOrd, Ord)]\npub enum {name} {{");
        for v in values {
            let _ = writeln!(out, "    {},", pascal(v));
        }
        out.push_str("}\n");
        let _ = writeln!(out, "impl {name} {{");
        let all: Vec<String> = values.iter().map(|v| format!("{name}::{}", pascal(v))).collect();
        let _ = writeln!(out, "    pub const ALL: &'static [{name}] = &[{}];", all.join(", "));
        out.push_str("    pub fn as_str(self) -> &'static str {\n        match self {\n");
        for v in values {
            let _ = writeln!(out, "            {name}::{} => {v:?},", pascal(v));
        }
        out.push_str("        }\n    }\n");
        let _ = writeln!(out, "    pub fn parse(s: &str) -> Option<{name}> {{\n        match s {{");
        for v in values {
            let _ = writeln!(out, "            {v:?} => Some({name}::{}),", pascal(v));
        }
        out.push_str("            _ => None,\n        }\n    }\n}\n\n");
    }

    for sheet in &sheets.sheets {
        let sn = &sheet.struct_name;
        let _ = writeln!(out, "/// One row of `design/{}.json`. {}", sheet.name, sheet.about.replace('\n', " "));
        let _ = writeln!(out, "#[derive(Debug, Clone, Copy)]\npub struct {sn} {{");
        for col in &sheet.columns {
            let _ = writeln!(out, "    pub {}: {},", col.name, field_type(sheet, col));
        }
        out.push_str("}\n");
        let _ = writeln!(
            out,
            "impl {sn} {{\n    pub fn find(id: &str) -> Option<&'static {sn}> {{\n        {}.iter().find(|r| r.id == id)\n    }}\n}}",
            sheet.name.to_uppercase()
        );
        let _ = writeln!(out, "pub static {}: &[{sn}] = &[", sheet.name.to_uppercase());
        for row in &sheet.rows {
            let _ = write!(out, "    {sn} {{ ");
            for col in &sheet.columns {
                let _ = write!(out, "{}: {}, ", col.name, literal(sheet, col, &row[&col.name]));
            }
            out.push_str("},\n");
        }
        out.push_str("];\n\n");
    }
    out
}
